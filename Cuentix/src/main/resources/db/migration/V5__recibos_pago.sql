BEGIN;

CREATE TABLE recibo_pago (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id INTEGER NOT NULL REFERENCES cuenta_credito,
    clave UUID NOT NULL,
    vencimiento DATE NOT NULL,
    fecha_pago DATE NOT NULL,
    moneda VARCHAR(255) NOT NULL,
    UNIQUE (cuenta_id, clave)
);

CREATE TABLE detalle_pago (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recibo_id INTEGER NOT NULL REFERENCES recibo_pago,
    cuota_id INTEGER NOT NULL UNIQUE REFERENCES cuota,
    mora NUMERIC(38,2) NOT NULL,
    interes NUMERIC(38,2) NOT NULL,
    capital NUMERIC(38,2) NOT NULL,
    interes_gracia NUMERIC(38,2) NOT NULL
);

CREATE INDEX detalle_pago_recibo_idx ON detalle_pago (recibo_id);

COMMIT;
