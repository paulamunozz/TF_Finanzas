CREATE TABLE cierre (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id INTEGER NOT NULL REFERENCES cuenta_credito, periodo DATE NOT NULL,
    corte TIMESTAMP NOT NULL, vencimiento DATE NOT NULL, moneda VARCHAR(255) NOT NULL,
    UNIQUE (cuenta_id, periodo)
);
CREATE TABLE linea_cierre (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cierre_id INTEGER NOT NULL REFERENCES cierre, cuota_id INTEGER NOT NULL REFERENCES cuota,
    capital NUMERIC(38,2), interes NUMERIC(38,2), mora NUMERIC(38,2), ajuste BOOLEAN NOT NULL,
    UNIQUE (cierre_id, cuota_id)
);
